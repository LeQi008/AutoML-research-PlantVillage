import json

from dotenv import load_dotenv
from openai import OpenAI
from tools import (
    list_files,
    list_experiments,
    read_file,
    run_experiment
)


load_dotenv()

client = OpenAI()


TOOLS = [
    {
        "type": "function",
        "name": "list_files",
        "description": "List the files in the AutoML Research Lab repository that the agent is allowed to access.",
        "parameters": {
            "type": "object",
            "properties": {},
            "required": [],
        },
    },
    {
        "type": "function",
        "name": "read_file",
        "description": "Read an accessible file from the AutoML Research Lab repository.",
        "parameters": {
            "type": "object",
            "properties": {
                "path": {
                    "type": "string",
                    "description": "Path to the file relative to the project root.",
                }
            },
            "required": ["path"],
        },
    },
    {
        "type": "function",
        "name": "list_experiments",
        "description": "List all completed AutoML experiments in the experiments directory.",
        "parameters": {
            "type": "object",
            "properties": {},
            "required": [],
        },
    },
    {
        "type": "function",
        "name": "run_experiment",
        "description": (
            "Run a machine learning experiment using the existing experiment "
            "pipeline. The experiment is based on the baseline configuration "
            "and selected parameters can be overridden. The experiment ID is "
            "automatically generated by the tool; do not provide an experiment ID."
        ),
        "parameters": {
            "type": "object",
            "properties": {
                "objective": {
                    "type": "string",
                    "description": (
                        "The objective or hypothesis being tested."
                    ),
                },
                "epochs": {
                    "type": "integer",
                    "description": "Number of training epochs.",
                },
                "learning_rate": {
                    "type": "number",
                    "description": "Learning rate.",
                },
                "batch_size": {
                    "type": "integer",
                    "description": "Training batch size.",
                },
                "model_name": {
                    "type": "string",
                    "description": "Model name to use.",
                },
            },
            "required": [],
        },
    },

    ]


def execute_tool(name, arguments):
    if name == "list_files":
        return list_files()

    if name == "read_file":
        return read_file(arguments["path"])

    if name == "list_experiments":
        return list_experiments()

    if name == "run_experiment":
        return run_experiment(
            objective=arguments.get("objective"),
            epochs=arguments.get("epochs"),
            learning_rate=arguments.get("learning_rate"),
            batch_size=arguments.get("batch_size"),
            model_name=arguments.get("model_name"),
        )

    print(f"Unknown tool: {name}")

    return f"Unknown tool: {name}"


def run_agent(conversation):

    while True:
        response = client.responses.create( # Repeat until no more tool call
            model="gpt-5.6-luna",
            input=conversation,
            tools=TOOLS,
        )

        conversation.extend(response.output)

        tool_calls = [
            item for item in response.output
            if item.type == "function_call"
        ]

        if not tool_calls: # if there is no tool call, we're done.
            return response.output_text
        
        for tool_call in tool_calls:
            print(f"\nTool requested: {tool_call.name}")
            print(f"Arguments: {tool_call.arguments}")
            arguments = json.loads(tool_call.arguments)

            print(f"Executing: {tool_call.name}({arguments})")
            result = execute_tool(
                tool_call.name,
                arguments,
            )

            conversation.append( # append the tool result to conversation
                { 
                    "type": "function_call_output",
                    "call_id": tool_call.call_id,
                    "output": result,
                }
            )


def main():
    print("AutoML Research Agent")
    print("Type 'exit' to quit.\n")

    conversation = []

    while True:
        user_input = input("You: ")

        if user_input.lower() == "exit":
            break

        conversation.append({
            "role": "user",
            "content": user_input,
        })

        response = run_agent(conversation)

        conversation.append({
            "role": "assistant",
            "content": response,
        })

        print(f"\nAgent: {response}\n")


if __name__ == "__main__":
    main()